function TwoToneHeading({ text, tag: Tag = "h2", className = "" }) {
  const words = text.trim().split(" ");
  const mid = Math.ceil(words.length / 2);
  const first = words.slice(0, mid).join(" ");
  const second = words.slice(mid).join(" ");
  return (
    <Tag className={className}>
      <span className="text-[var(--color-primary)]">{first}</span>
      {second && (
        <>
          <span className="text-[var(--color-accent)]"> {second}</span>
        </>
      )}
    </Tag>
  );
}

function renderContent(content) {
  return content.map((block, i) => {
    if (block.type === "text") {
      return (
        <p key={i} className=" leading-relaxed text-[19px]">
          {block.text}
        </p>
      );
    }
    if (block.type === "bullets") {
      return (
        <ul key={i} className="space-y-2 pl-1">
          {block.items.map((item, j) => (
            <li key={j} className="flex items-start gap-3  text-[19px]">
              <span className="mt-[6px] w-1.5 h-1.5 rounded-full bg-[var(--color-accent)] shrink-0" />
              {item}
            </li>
          ))}
        </ul>
      );
    }
    if (block.type === "list") {
      return (
        <ul key={i} className="space-y-3">
          {block.items.map((item, j) => (
            <li
              key={j}
              className="flex flex-col sm:flex-row sm:items-baseline gap-1 sm:gap-2 text-[19px]"
            >
              <span className="font-semibold text-[var(--color-primary)] shrink-0">
                {item.term}:
              </span>
              <span>{item.def}</span>
            </li>
          ))}
        </ul>
      );
    }
    return null;
  });
}

